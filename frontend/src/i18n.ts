const TABLES: Record<Lang, Labels> = { hi, en };

/** Label for `key` in `lang`. */
export function t(lang: Lang, key: LabelKey): string {
  return TABLES[lang][key];
}

/** The full table for one language, for components that need several labels. */
export function labels(lang: Lang): Labels {
  return TABLES[lang];
}

/** Anything that is not "en" is Hindi / Hinglish, as on the server. */
export function normalizeLang(v: unknown): Lang {
  return v === 'en' ? 'en' : 'hi';
}
